export function catalogoVisible(rows) {
  const source = rows?.length ? rows : CATALOGO_INICIAL;
  return [...source].sort((a, b) => (Number(a.orden) || 0) - (Number(b.orden) || 0));
}

export function incluyeDe(item) {
  return String(item?.incluye || "").split("\n").map((line) => line.trim()).filter(Boolean);
}
